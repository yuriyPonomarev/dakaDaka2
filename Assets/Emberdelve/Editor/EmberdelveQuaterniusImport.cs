using System;
using System.Collections.Generic;
using System.IO;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;

namespace Emberdelve.EditorTools
{
    /// <summary>
    /// V3b: import settings + manifest for the CC0 Quaternius Universal Animation Library 1 + 2 (Standard), the animated humanoid
    /// mannequin that the grim undead enemies are built from (<see cref="EmberdelveEnemyVisualFactory"/>).
    ///
    /// Files were downloaded once from OpenGameArt (see <see cref="Files"/>) and live byte for byte under
    /// Assets/Emberdelve/Art/ThirdParty/Quaternius/. This class:
    ///   * OnPreprocessModel: Humanoid rig, avatar created from the model itself, no cameras / lights / colliders / materials
    ///     (the project builds its own URP materials), bones kept (hand lookup), animation imported on the two library files only.
    ///   * <see cref="EnsureConfigured"/>: per-clip settings (loop flags for locomotion / idle clips, root position and rotation
    ///     baked into the pose so a clip never moves the root - the EnemyAgent moves it). Idempotent: reimports only on change.
    ///   * <see cref="WriteManifest"/>: manifest.json (source, author, license, sha256, size of every file) + LICENSE_CC0.txt.
    /// Menu: Emberdelve/Visual/Configure Quaternius Assets.
    /// </summary>
    public sealed class EmberdelveQuaterniusImport : AssetPostprocessor
    {
        public const string Root = "Assets/Emberdelve/Art/ThirdParty/Quaternius";
        public const string ManifestPath = Root + "/manifest.json";
        public const string LicensePath = Root + "/LICENSE_CC0.txt";
        public const string Ual1Path = Root + "/UAL1/AnimationLibrary_Unity_Standard.fbx";
        public const string Ual2Path = Root + "/UAL2/UAL2_Standard.fbx";
        public const string MannequinFPath = Root + "/UAL2/Mannequin_F.fbx";
        public const string LicenseUrl = "https://creativecommons.org/publicdomain/zero/1.0/";

        /// <summary>Clips whose name matches play in a loop (idle, locomotion). Everything else (attacks, hits, deaths) plays once.</summary>
        public static readonly Regex LoopPattern = new Regex("(idle|walk|run|jog|sprint|loop|crouch_fwd|shamble)", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);

        [Serializable] public sealed class ManifestFile { public string path; public string source; public string sha256; public long bytes; public bool animations; }

        [Serializable]
        public sealed class Manifest
        {
            public string schema = "emberdelve-quaternius-manifest/1";
            public string name = "Quaternius Universal Animation Library 1 + 2 (Standard)";
            public string creator = "Quaternius (https://quaternius.com)";
            public string license = "CC0-1.0";
            public string license_url = LicenseUrl;
            public string note = "Files are byte for byte what the sources serve. Import settings (Humanoid, loop flags, baked root) come from EmberdelveQuaterniusImport; the undead materials are generated by EmberdelveUndeadMaterials.";
            public List<ManifestFile> files = new List<ManifestFile>();
        }

        /// <summary>Path, source page, expected sha256 (of the file as downloaded), carries animation clips.</summary>
        public static readonly string[][] Files =
        {
            new[] { Ual1Path, "https://opengameart.org/node/174563 (universal_animation_librarystandard.zip)", "42f16a4ed61d1e9f5fc7c2526894c5487148ac6ba82b64281ceb7943570f3c37", "1" },
            new[] { Ual2Path, "https://opengameart.org/content/universal-animation-library-2 (universal_animation_library_2standard.zip)", "d4a2dd67bb12bf0c01891bc59ee697e04db679d26883d30bd937c2f3fb6fec90", "1" },
            new[] { MannequinFPath, "https://opengameart.org/content/universal-animation-library-2 (universal_animation_library_2standard.zip)", "890784432838b1f4f9194fd6011769888872a7ba7f3159689771e1998c96a42c", "0" },
        };

        public static bool IsQuaternius(string assetPath) { return assetPath != null && assetPath.StartsWith(Root + "/", StringComparison.Ordinal); }

        // ---------------------------------------------------------------- import pipeline

        private void OnPreprocessModel()
        {
            if (!IsQuaternius(assetPath) || !assetPath.EndsWith(".fbx", StringComparison.OrdinalIgnoreCase)) return;
            ApplyModelSettings((ModelImporter)assetImporter, assetPath);
        }

        /// <summary>Rig / mesh settings. Returns true when something changed.</summary>
        public static bool ApplyModelSettings(ModelImporter importer, string path)
        {
            bool changed = false;
            bool animations = path != MannequinFPath;

            if (importer.animationType != ModelImporterAnimationType.Human) { importer.animationType = ModelImporterAnimationType.Human; changed = true; }
            if (importer.avatarSetup != ModelImporterAvatarSetup.CreateFromThisModel) { importer.avatarSetup = ModelImporterAvatarSetup.CreateFromThisModel; changed = true; }
            if (importer.importAnimation != animations) { importer.importAnimation = animations; changed = true; }
            if (importer.optimizeGameObjects) { importer.optimizeGameObjects = false; changed = true; }
            if (importer.importCameras) { importer.importCameras = false; changed = true; }
            if (importer.importLights) { importer.importLights = false; changed = true; }
            if (importer.addCollider) { importer.addCollider = false; changed = true; }
            if (importer.importBlendShapes) { importer.importBlendShapes = false; changed = true; }
            // Readable: the undead material texture is baked from the mesh (height / UV layout), see EmberdelveUndeadMaterials.
            if (!importer.isReadable) { importer.isReadable = true; changed = true; }
            if (importer.materialImportMode != ModelImporterMaterialImportMode.None) { importer.materialImportMode = ModelImporterMaterialImportMode.None; changed = true; }
            return changed;
        }

        // ---------------------------------------------------------------- configure (clips) + manifest

        [MenuItem("Emberdelve/Visual/Configure Quaternius Assets")]
        public static void ConfigureMenu() { Debug.Log("[Emberdelve][Quaternius] " + (EnsureConfigured() ? "configured" : "files missing")); }

        /// <summary>Imports the three files with the project settings, sets the per-clip flags and writes the manifest. Idempotent. False when a file is missing.</summary>
        public static bool EnsureConfigured()
        {
            bool allPresent = true;
            for (int i = 0; i < Files.Length; i++)
            {
                if (!File.Exists(Absolute(Files[i][0]))) { Debug.LogWarning("[Emberdelve][Quaternius] missing " + Files[i][0]); allPresent = false; }
            }

            if (!allPresent) return false;

            AssetDatabase.Refresh();
            for (int i = 0; i < Files.Length; i++)
            {
                ModelImporter importer = AssetImporter.GetAtPath(Files[i][0]) as ModelImporter;
                if (importer == null) { Debug.LogWarning("[Emberdelve][Quaternius] no importer for " + Files[i][0]); allPresent = false; continue; }

                bool changed = ApplyModelSettings(importer, Files[i][0]);
                if (Files[i][3] == "1") changed |= ApplyClipSettings(importer);
                if (changed) importer.SaveAndReimport();
            }

            WriteManifest();
            return allPresent;
        }

        /// <summary>Per-clip settings; the clip list is the importer's defaults (every take of the file) with project flags. True when changed.</summary>
        public static bool ApplyClipSettings(ModelImporter importer)
        {
            ModelImporterClipAnimation[] source = importer.clipAnimations;
            if (source == null || source.Length == 0) source = importer.defaultClipAnimations;
            if (source == null || source.Length == 0) return false;

            bool changed = importer.clipAnimations == null || importer.clipAnimations.Length != source.Length;
            ModelImporterClipAnimation[] clips = new ModelImporterClipAnimation[source.Length];
            for (int i = 0; i < source.Length; i++)
            {
                ModelImporterClipAnimation c = source[i];
                bool loop = LoopPattern.IsMatch(c.name);
                if (c.loopTime != loop) { c.loopTime = loop; changed = true; }
                if (c.loopPose != loop) { c.loopPose = loop; changed = true; }

                // The agent moves the root transform: rotation and XZ position are baked into the pose, height keeps the original.
                if (!c.lockRootRotation) { c.lockRootRotation = true; changed = true; }
                if (!c.lockRootPositionXZ) { c.lockRootPositionXZ = true; changed = true; }
                if (c.keepOriginalPositionXZ) { c.keepOriginalPositionXZ = false; changed = true; }
                if (!c.lockRootHeightY) { c.lockRootHeightY = true; changed = true; }
                if (!c.keepOriginalPositionY) { c.keepOriginalPositionY = true; changed = true; }
                clips[i] = c;
            }

            if (changed) importer.clipAnimations = clips;
            return changed;
        }

        public static Manifest BuildManifest()
        {
            Manifest manifest = new Manifest();
            for (int i = 0; i < Files.Length; i++)
            {
                string absolute = Absolute(Files[i][0]);
                manifest.files.Add(new ManifestFile
                {
                    path = Files[i][0],
                    source = Files[i][1],
                    sha256 = File.Exists(absolute) ? Sha256(absolute) : "",
                    bytes = File.Exists(absolute) ? new FileInfo(absolute).Length : 0,
                    animations = Files[i][3] == "1",
                });
            }

            return manifest;
        }

        public static void WriteManifest()
        {
            string json = JsonUtility.ToJson(BuildManifest(), true) + "\n";
            string path = Absolute(ManifestPath);
            if (!File.Exists(path) || File.ReadAllText(path) != json) File.WriteAllText(path, json, new UTF8Encoding(false));

            const string license =
                "Quaternius - Universal Animation Library (Standard) 1 and 2, mannequin models and animations.\n" +
                "Author: Quaternius (https://quaternius.com)\n" +
                "Sources: https://opengameart.org/node/174563 and https://opengameart.org/content/universal-animation-library-2\n\n" +
                "License: CC0 1.0 Universal (public domain dedication), https://creativecommons.org/publicdomain/zero/1.0/\n" +
                "The work may be copied, modified, distributed and used, even commercially, without asking permission. Credit is appreciated, not required.\n" +
                "The original License.txt files of the packs sit next to the FBX files (UAL1/, UAL2/).\n";
            string licensePath = Absolute(LicensePath);
            if (!File.Exists(licensePath) || File.ReadAllText(licensePath) != license) File.WriteAllText(licensePath, license, new UTF8Encoding(false));
            AssetDatabase.Refresh();
        }

        public static Manifest ReadManifest()
        {
            string path = Absolute(ManifestPath);
            if (!File.Exists(path)) return null;
            try { return JsonUtility.FromJson<Manifest>(File.ReadAllText(path)); } catch (Exception) { return null; }
        }

        public static string Sha256(string absolutePath)
        {
            using (SHA256 sha = SHA256.Create())
            using (FileStream stream = File.OpenRead(absolutePath))
            {
                byte[] hash = sha.ComputeHash(stream);
                StringBuilder sb = new StringBuilder(hash.Length * 2);
                for (int i = 0; i < hash.Length; i++) sb.Append(hash[i].ToString("x2"));
                return sb.ToString();
            }
        }

        public static string Absolute(string assetPath)
        {
            return Path.GetFullPath(Path.Combine(Application.dataPath, "..", assetPath));
        }
    }
}
