        /// <summary>
        /// D1a: authors the swing patterns of the player's melee weapons as ScriptableObject data and assigns them
        /// to the weapon assets, and the hit-location table. Idempotent and code-authoritative like the other Apply
        /// passes: every run rewrites the pattern fields from the numbers below, so a retune is an edit here plus a
        /// data build. All numbers are our own tunables (Docs/Tasks/D1a.md). Geometry is in the attacker's aim frame
        /// (x right, y up, z forward, metres from the eye; yaw right-positive, pitch DOWN-positive, degrees) and
        /// was tuned so the swing crosses the crosshair line at about 2 m.
        /// </summary>
        private static void ApplySwingPatterns()
        {
            // H1 retune (review D1a): reach and speed toward the reference genre. The segment is a 1.2 m blade held at
            // arm's length (the hand sweeps an 0.85 m arc around the shoulder), effective reach (2.3 + 0.6) x 0.79 =
            // 2.29 m from the eye, a 110 degree slash with a 0.30 s active phase. Our own tunables.
            if (Sword != null && !Mathf.Approximately(Sword.activeWindow, 0.30f))
            {
                Sword.activeWindow = 0.30f;
                EditorUtility.SetDirty(Sword);
            }

            SwordSlashLeftToRight = AuthorPattern("Pattern_SwordSlashLR", "sword_slash_lr", SwingKind.HorizontalLeftToRight, Sword,
                0.79f, 0.94f, 0.15f, 0.020f, 4, 1f, ArcKeys(true));
            SwordSlashRightToLeft = AuthorPattern("Pattern_SwordSlashRL", "sword_slash_rl", SwingKind.HorizontalRightToLeft, Sword,
                0.79f, 0.94f, 0.15f, 0.020f, 4, 1f, ArcKeys(false));

            // Overhead: slower and heavier, the hand comes down from above the head through the line of fire.
            SwordOverhead = AuthorPattern("Pattern_SwordOverhead", "sword_overhead", SwingKind.Overhead, Sword,
                0.79f, 0.94f, 0.15f, 0.016f, 2, 1f,
                new SwingKey(0f, new Vector3(0.15f, 0.55f, 0.35f), 2f, -80f),
                new SwingKey(0.5f, new Vector3(0.15f, 0.15f, 0.80f), 2f, -25f),
                new SwingKey(1f, new Vector3(0.15f, -0.25f, 0.90f), 2f, 35f));
            SetPatternTiming(SwordOverhead, 0.34f, 0.32f, 0.38f);
            SwordRiposteCut = AuthorPattern("Pattern_SwordRiposteCut", "sword_riposte_cut", SwingKind.Overhead, Sword,
                0.79f, 0.94f, 0.15f, 0.018f, 3, 1f,
                new SwingKey(0f, new Vector3(0.45f, 0.50f, 0.40f), 35f, -60f),
                new SwingKey(0.5f, new Vector3(0.10f, 0.10f, 0.90f), -10f, 5f),
                new SwingKey(1f, new Vector3(-0.35f, -0.30f, 0.75f), -45f, 40f));
            SetPatternTiming(SwordRiposteCut, 0.36f, 0.30f, 0.36f);
            SetPatternTiming(SwordSlashLeftToRight, 0.24f, 0.30f, 0.30f);
            SetPatternTiming(SwordSlashRightToLeft, 0.24f, 0.30f, 0.30f);

            // Rapier thrust: a narrow line straight ahead, reach (2.7 + 0.45) x 0.74 = 2.33 m. Not an arc: a target 20
            // degrees off the line is missed at range - the documented consequence of a thrust.
            RapierThrust = AuthorPattern("Pattern_RapierThrust", "rapier_thrust", SwingKind.Thrust, Rapier,
                0.74f, 1.08f, 0.10f, 0.020f, 2, 1f,
                new SwingKey(0f, new Vector3(0.20f, -0.22f, 0.30f), -6f, -5f),
                new SwingKey(1f, new Vector3(0.20f, -0.22f, 1.08f), -6f, -5f));

            AssignPatterns(Sword, SwordSlashRightToLeft, SwordSlashLeftToRight, SwordOverhead, SwordRiposteCut); // Dark and Darker order: the chain opens right-to-left; 3 = riposte cut
            AssignPatterns(Rapier, RapierThrust);

            // U5A: the fist punch, a short straight thrust (our own tunables), and the hand rule of the ranged weapons: they fill both hands.
            FistPunch = AuthorPattern("Pattern_FistPunch", "fist_punch", SwingKind.Thrust, Fists,
                0.74f, 0.80f, 0.10f, 0.020f, 1, 1f,
                new SwingKey(0f, new Vector3(0.20f, -0.22f, 0.25f), -6f, -5f),
                new SwingKey(1f, new Vector3(0.20f, -0.22f, 0.80f), -6f, -5f));
            AssignPatterns(Fists, FistPunch);
            if (Fists != null && !Fists.isUnarmed) { Fists.isUnarmed = true; EditorUtility.SetDirty(Fists); }
            foreach (WeaponData ranged in new[] { Bow, Crossbow })
            {
                if (ranged != null && !ranged.twoHanded) { ranged.twoHanded = true; EditorUtility.SetDirty(ranged); }
            }

            HitLocations = LoadOrCreate<HitLocationTable>(EmberdelvePaths.Data + "/HitLocationTable.asset", t => { });
            if (HitLocations != null
                && (!Mathf.Approximately(HitLocations.head, HitLocationTable.DefaultHead) || !Mathf.Approximately(HitLocations.body, HitLocationTable.DefaultBody)
                    || !Mathf.Approximately(HitLocations.arms, HitLocationTable.DefaultArms) || !Mathf.Approximately(HitLocations.hands, HitLocationTable.DefaultHands)
                    || !Mathf.Approximately(HitLocations.legs, HitLocationTable.DefaultLegs) || !Mathf.Approximately(HitLocations.feet, HitLocationTable.DefaultFeet)))
            {
                HitLocations.head = HitLocationTable.DefaultHead;
                HitLocations.body = HitLocationTable.DefaultBody;
                HitLocations.arms = HitLocationTable.DefaultArms;
                HitLocations.hands = HitLocationTable.DefaultHands;
                HitLocations.legs = HitLocationTable.DefaultLegs;
                HitLocations.feet = HitLocationTable.DefaultFeet;
                EditorUtility.SetDirty(HitLocations);
            }

            AssetDatabase.SaveAssets();
        }

        /// <summary>
        /// D1c4: gives the two enemy weapons a swing pattern, so a real monster attacks through the authority's swept swing
        /// like the player. Code-authoritative and idempotent like ApplySwingPatterns; it runs after BuildEnemies because the
        /// pattern is authored FROM the enemy: its yaw range is the enemy's <c>attackTelegraphCone</c> (the warned wedge and the
        /// sweep are one source), its reach is the weapon's own reach (reachScale 1, so the effective reach is
        /// weapon.reach + weapon.hitSphereRadius, the number the old telegraph already drew). One combo step of damage x1, NO
        /// impact zones on the weapons (so the claw is not scaled by where along the blade it lands: the hit-location table is
        /// the only damage variance). Windup 0.10 s and active 0.18 s are the proposal values (EnemySwingWindup / EnemySwingActive);
        /// the brain's own attackWindup stays the telegraph and the swing begins when the brain asks for the attack. The weapons'
        /// older windupTime / activeWindow / recoveryTime fields are not read by the swept path and are left as they were.
        /// </summary>
        private static void ApplyEnemySwings()
        {
            ClawSlash = AuthorEnemyPattern("Pattern_ClawSlash", "claw_slash", Claw, Servitor, 0.60f, 0.18f, -0.20f, 0.40f);
            MaulSweep = AuthorEnemyPattern("Pattern_MaulSweep", "maul_sweep", ClawElite, Warden, 0.70f, 0.22f, -0.10f, 0.50f);

            AssignPatterns(Claw, ClawSlash);
            AssignPatterns(ClawElite, MaulSweep);

            // A one-step "chain" would only add a second place to author the multiplier; the weapons stay chainless (step 0 only).
            // No impact zones: a contact anywhere along the blade does full damage.
            foreach (WeaponData weapon in new[] { Claw, ClawElite })
            {
                if (weapon == null) continue;
                bool dirty = false;
                if (weapon.comboSteps != null && weapon.comboSteps.Length != 0) { weapon.comboSteps = new ComboStep[0]; dirty = true; }
                if (weapon.impactZones != null && weapon.impactZones.Length != 0) { weapon.impactZones = new ImpactZone[0]; dirty = true; }
                if (dirty) EditorUtility.SetDirty(weapon);
            }

            AssetDatabase.SaveAssets();
        }

        /// <summary>
        /// One enemy pattern: five keys on the arc of a short arm. The hand travels a circle of radius <paramref name="handRadius"/>
        /// around the eye (the pattern's reachInset is that radius, so the tip reaches exactly the weapon's reach) at height
        /// <paramref name="handY"/> below the eye, and the blade points along the arm, from -cone/2 to +cone/2 of the committed direction.
        /// </summary>
        private static SwingPatternData AuthorEnemyPattern(string assetName, string patternId, WeaponData weapon, EnemyData enemy,
            float handRadius, float sweepRadius, float handY, float recovery)
        {
            if (weapon == null || enemy == null) return null;

            float cone = Mathf.Clamp(enemy.attackTelegraphCone, 40f, 200f);
            if (!Mathf.Approximately(cone, enemy.attackTelegraphCone))
            {
                enemy.attackTelegraphCone = cone;
                EditorUtility.SetDirty(enemy);
            }

            float half = cone * 0.5f;
            SwingKey[] keys = new SwingKey[5];
            for (int i = 0; i < keys.Length; i++)
            {
                float yaw = half - cone * (i / 4f);   // the shared Sword_Regular_A attack clip moves the hand from the attacker's right to the left
                float r = yaw * Mathf.Deg2Rad;
                keys[i] = new SwingKey(i / 4f, new Vector3(handRadius * Mathf.Sin(r), handY, handRadius * Mathf.Cos(r)), yaw, -2f);
            }

            SwingPatternData p = AuthorPattern(assetName, patternId, SwingKind.HorizontalLeftToRight, weapon,
                1f, handRadius, sweepRadius, 0.020f, 2, 1f, keys);
            if (p == null) return null;

            SetPatternTiming(p, EnemySwingWindup, EnemySwingActive, recovery);
            p.wallRecoilTime = 0.30f;
            EditorUtility.SetDirty(p);
            return p;
        }

